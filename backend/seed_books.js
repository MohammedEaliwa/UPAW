db.serialize(() => {
  db.run(`CREATE TABLE IF NOT EXISTS books (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    serial_number TEXT,
    title TEXT NOT NULL
  )`);

  db.get("SELECT count(*) as count FROM books", (err, row) => {
    if (err) {
      console.error(err);
      process.exit(1);
    }
    if (row.count === 0) {
      console.log('Inserting ' + books.length + ' books...');
      const stmt = db.prepare(`INSERT INTO books (serial_number, title) VALUES (?, ?)`);
      books.forEach(b => {
        stmt.run(b[0], b[1]);
      });
      stmt.finalize((err2) => {
        if (err2) {
          console.error(err2);
          process.exit(1);
        }
        console.log('Seeding books successful!');
        process.exit(0);
      });
    } else {
      console.log('Books table already has data. Skipping seed.');
      process.exit(0);
    }
  });
});
